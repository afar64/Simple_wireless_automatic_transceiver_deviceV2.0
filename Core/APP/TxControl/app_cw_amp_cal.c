static uint32_t App_CwAmpCalClampFreq(uint32_t freq_hz)
{
  if (freq_hz < APP_CW_AMP_CAL_FREQ_MIN_HZ) { return APP_CW_AMP_CAL_FREQ_MIN_HZ; }
  if (freq_hz > APP_CW_AMP_CAL_FREQ_MAX_HZ) { return APP_CW_AMP_CAL_FREQ_MAX_HZ; }
  return freq_hz;
}

static uint16_t App_CwAmpCalClampTarget(uint16_t target_mvrms)
{
  if (target_mvrms < APP_CW_AMP_CAL_TARGET_MIN_MVRMS) { return APP_CW_AMP_CAL_TARGET_MIN_MVRMS; }
  if (target_mvrms > APP_CW_AMP_CAL_TARGET_MAX_MVRMS) { return APP_CW_AMP_CAL_TARGET_MAX_MVRMS; }
  return target_mvrms;
}

int App_CwAmpCal_Lookup(uint32_t freq_hz, uint16_t target_mvrms, AppCwAmpCalResult *result)
{
  uint32_t clamped_freq;
  uint32_t freq_index;
  uint16_t clamped_target;
  uint32_t target_index;

  if (result == 0) { return -1; }
  clamped_freq = App_CwAmpCalClampFreq(freq_hz);
  freq_index = (clamped_freq - APP_CW_AMP_CAL_FREQ_MIN_HZ + (APP_CW_AMP_CAL_FREQ_STEP_HZ / 2UL)) / APP_CW_AMP_CAL_FREQ_STEP_HZ;
  if (freq_index >= APP_CW_AMP_CAL_FREQ_COUNT) { freq_index = APP_CW_AMP_CAL_FREQ_COUNT - 1U; }
  clamped_target = App_CwAmpCalClampTarget(target_mvrms);
  target_index = ((uint32_t)clamped_target + (APP_CW_AMP_CAL_TARGET_STEP_MVRMS / 2U) - APP_CW_AMP_CAL_TARGET_MIN_MVRMS) / APP_CW_AMP_CAL_TARGET_STEP_MVRMS;
  if (target_index >= APP_CW_AMP_CAL_TARGET_COUNT) { target_index = APP_CW_AMP_CAL_TARGET_COUNT - 1U; }
  *result = s_cw_amp_cal_table[freq_index][target_index];
  return 0;
}
